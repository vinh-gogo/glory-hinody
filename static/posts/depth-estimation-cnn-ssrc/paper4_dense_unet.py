import tensorflow as tf
from tensorflow.keras.layers import Input, Conv2D, MaxPooling2D, UpSampling2D
from tensorflow.keras.models import Model

def create_res_network(input_shape, k1=32):
    '''Base/ResNet101 network'''
    input = Input(shape=input_shape)
    x = tf.keras.applications.resnet.preprocess_input(input)
    core =  tf.keras.applications.ResNet50(include_top=False, weights=None, pooling=None)
    x = core(x)

    encoded = Conv2D(1, (3, 3), activation='elu', padding='same', kernel_regularizer = tf.keras.regularizers.L2(0.0001), activity_regularizer=tf.keras.regularizers.L2(0.0001), bias_regularizer=tf.keras.regularizers.L2(0.0001))(x)
    encoded = Conv2D(1, (3, 3), activation='sigmoid', padding='same', kernel_regularizer = tf.keras.regularizers.L2(0.0001), activity_regularizer=tf.keras.regularizers.L2(0.0001), bias_regularizer=tf.keras.regularizers.L2(0.0001))(encoded)
    decoded = Conv2D(1, (3, 3), activation='sigmoid', padding='same', kernel_regularizer = tf.keras.regularizers.L2(0.0001), activity_regularizer=tf.keras.regularizers.L2(0.0001), bias_regularizer=tf.keras.regularizers.L2(0.0001))(encoded)
    mod = Model(input, decoded)
    return mod

