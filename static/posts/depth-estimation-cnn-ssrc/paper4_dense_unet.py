def lam_sat_net_float_sau_median_ngan(anh_xam_float, kich_thuoc_median=3, kich_thuoc_gaussian=(3, 3), luong_sac_net=1.0):
    """Làm sắt nét ảnh xám (float 0-1) sau lọc median."""
    # Chuyển tạm sang uint8 cho median blur, sau đó về float 0-1
    anh_uint8 = (anh_xam_float * 255.0).astype(np.uint8)
    anh_sau_median_uint8 = cv2.medianBlur(anh_uint8, kich_thuoc_median)
    anh_sau_median_float = anh_sau_median_uint8.astype(np.float32) / 255.0

    # Unsharp Masking

    # anh_mo_float = cv2.medianBlur(anh_sau_median_float, kich_thuoc_median)
    anh_mo_float = cv2.GaussianBlur(anh_sau_median_float, kich_thuoc_gaussian, 0)
    mask = anh_sau_median_float - anh_mo_float
    anh_sac_net_float = anh_sau_median_float + luong_sac_net * mask

    # Giới hạn về 0-1
    anh_sac_net_float = np.clip(anh_sac_net_float, 0.0, 1.0)

    return anh_sac_net_float

def remove_outliers_per_image(images, z_thresh=10.0):
    """
    Loại bỏ các điểm ảnh ngoại lai trong mỗi ảnh bằng phương pháp z-score.
    Các điểm ảnh có z-score > z_thresh sẽ được thay bằng giá trị trung vị của ảnh.
    images: numpy array, shape (N, H, W) hoặc (N, H, W, 1)
    z_thresh: ngưỡng z-score để xác định ngoại lai
    """
    images_out = []
    for img in images:
        img_flat = img.flatten()
        mean = np.mean(img_flat)
        std = np.std(img_flat)
        if std == 0:
            images_out.append(img)
            continue
        z_scores = (img_flat - mean) / std
        mask = np.abs(z_scores) > z_thresh
        img_flat[mask] = np.median(img_flat)
        img_out = img_flat.reshape(img.shape)
        images_out.append(img_out)
    return np.array(images_out)

