class SwinTransformerBlock(layers.Layer):
    def __init__(self, dim, num_patch, num_heads, window_size=7, shift_size=0, num_mlp=1024,
                 qkv_bias=True, qk_scale=None, mlp_drop=0, attn_drop=0, proj_drop=0, drop_path_prob=0, name='', **kwargs):
        super().__init__(**kwargs)

        self.dim = dim # number of input dimensions
        self.num_patch = num_patch # number of embedded patches; a tuple of  (heigh, width)
        self.num_heads = num_heads # number of attention heads
        self.window_size = window_size # size of window
        self.shift_size = shift_size # size of window shift
        self.num_mlp = num_mlp # number of MLP nodes
        self.qkv_bias = qkv_bias
        self.qk_scale = qk_scale
        self.mlp_drop = mlp_drop
        self.attn_drop = attn_drop
        self.proj_drop = proj_drop
        self.drop_path_prob = drop_path_prob
        self.prefix = name

        if self.shift_size > self.window_size:
            raise ValueError("shift_size cannot be greater than window_size")

        self.norm1 = LayerNormalization(epsilon=1e-5, name='{}_norm1'.format(self.prefix))
        self.attn = WindowAttention(
            dim=self.dim,
            window_size=(self.window_size, self.window_size),
            num_heads=self.num_heads,
            qkv_bias=self.qkv_bias,
            qk_scale=self.qk_scale,
            attn_drop=self.attn_drop,
            proj_drop=self.proj_drop,
        )
        self.drop_path = drop_path(drop_path_prob)
        self.norm2 = LayerNormalization(epsilon=1e-5, name='{}_norm1'.format(self.prefix))

        self.mlp = Mlp([num_mlp, dim], drop=mlp_drop, name=self.prefix)
        # self.mlp = Mlp(
        #     in_features=self.dim,
        #     hidden_features=int(self.dim * self.mlp_ratio),
        #     out_features=self.dim,
        #     act_layer=tf.nn.gelu,
        #     drop=self.drop_rate
        # )

        # Build attention mask if shift_size > 0 (for shifted window attention)
        if self.shift_size > 0:
            # Mask generation logic (usually done once in build or __init__)
            # This part typically depends on the feature map resolution for this stage
            # and might need to be created dynamically based on input_shape in call
            # or pre-calculated for fixed resolutions.
            # For simplicity, we'll create it directly in call for now,
            # but in a real Swin implementation, it's often more optimized.
            self.build_mask_on_call = True
        else:
            self.build_mask_on_call = False

    def build(self, input_shape):
        # input_shape: (batch_size, num_patches, embed_dim)
        # Chúng ta cần H và W để tạo mask, sẽ lấy từ input_shape ở call
        super().build(input_shape)

    def call(self, x, training=False):
        B, L, C = tf.shape(x) # L = H * W
        H_in = W_in = tf.cast(tf.sqrt(tf.cast(L, tf.float32)), tf.int32) # Giả sử hình vuông

        shortcut = x
        x = self.norm1(x)

        # Reshape từ (B, L, C) về (B, H, W, C)
        x = tf.reshape(x, (B, H_in, W_in, C))

        # Áp dụng padding nếu cần
        x_padded, pad_H, pad_W = pad_to_multiple(x, self.window_size)
        H_padded, W_padded = tf.shape(x_padded)[1], tf.shape(x_padded)[2]

        # Nếu shift_size > 0, thực hiện cyclic shift
        if self.shift_size > 0:
            shifted_x = tf.roll(x_padded, shift=[-self.shift_size, -self.shift_size], axis=[1, 2])
            # Tạo attention mask nếu shift_size > 0
            img_mask = tf.zeros((1, H_padded, W_padded, 1))
            h_slices = (slice(0, -self.window_size),
                        slice(-self.window_size, -self.shift_size),
                        slice(-self.shift_size, None))
            w_slices = (slice(0, -self.window_size),
                        slice(-self.window_size, -self.shift_size),
                        slice(-self.shift_size, None))
            cnt = 0
            for h in h_slices:
                for w in w_slices:
                    img_mask = tf.tensor_scatter_nd_update(img_mask, [[0, h.start or 0, w.start or 0, 0]], [tf.cast(cnt, tf.float32)])
                    cnt += 1

            mask_windows = window_partition(img_mask, self.window_size)
            mask_windows = tf.reshape(mask_windows, [-1, self.window_size * self.window_size])
            attn_mask = tf.expand_dims(mask_windows, axis=1) - tf.expand_dims(mask_windows, axis=2)
            attn_mask = tf.where(attn_mask != 0, -100.0, 0.0) # Sử dụng -100.0 cho các khu vực bị mask
        else:
            shifted_x = x_padded
            attn_mask = None # Không có mask nếu shift_size = 0

        # Chia cửa sổ
        x_windows = window_partition(shifted_x, self.window_size)
        # Flatten cửa sổ
        x_windows = tf.reshape(x_windows, (-1, self.window_size * self.window_size, C))

        # Áp dụng Attention
        attn_windows = self.attn(x_windows, mask=attn_mask, training=training)

        # Nối lại các cửa sổ
        attn_windows = tf.reshape(attn_windows, (-1, self.window_size, self.window_size, C))
        shifted_x = window_unpartition(attn_windows, self.window_size, H_padded, W_padded, C)

        # Đảo ngược cyclic shift nếu có
        if self.shift_size > 0:
            x = tf.roll(shifted_x, shift=[self.shift_size, self.shift_size], axis=[1, 2])
        else:
            x = shifted_x

        # Bỏ padding nếu có
        if pad_H > 0 or pad_W > 0:
            x = x[:, :H_in, :W_in, :] # Cắt bỏ phần padding

        # Reshape về dạng chuỗi lại
        x = tf.reshape(x, (B, L, C))

        # Add shortcut và MLP
        x = shortcut + self.drop_path(x, training=training)
        x = x + self.drop_path(self.mlp(self.norm2(x)), training=training)
        return x

    def compute_output_shape(self, input_shape):
        return input_shape # Swin Transformer Block giữ nguyên hình dạng đầu vào

    def get_config(self):
        config = super(SwinTransformerBlock, self).get_config()
        config.update({   "dim" : self.dim,
                          "num_patch" : self.num_patch,
                          "num_heads" : self.num_heads,
                          "window_size" : self.window_size,
                          "shift_size" : self.shift_size,
                          "num_mlp" : self.num_mlp,
                          "qkv_bias" : self.qkv_bias,
                          "qk_scale" : self.qk_scale,
                          "mlp_drop" : self.mlp_drop,
                          "attn_drop" : self.attn_drop,
                          "proj_drop" : self.proj_drop,
                          "drop_path_prob" : self.drop_path_prob})
        return config



