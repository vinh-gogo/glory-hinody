    decoded  = Conv2D(512, (3, 3), activation='elu', padding='same')(decoded)
    decoded  = Conv2D(512, (3, 3), activation='elu', padding='same')(decoded)
    decoded  = Conv2D(512, (3, 3), activation='elu', padding='same')(decoded)

