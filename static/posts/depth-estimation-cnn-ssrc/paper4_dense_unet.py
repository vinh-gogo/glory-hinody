# Hàm padding (đặt bên ngoài lớp SwinTransformerBlock nếu nó là hàm tiện ích chung)
def pad_to_multiple(x, multiple):
    B, H, W, C = tf.shape(x)
    pad_H = (multiple - H % multiple) % multiple
    pad_W = (multiple - W % multiple) % multiple

    if pad_H > 0 or pad_W > 0:
        paddings = [[0, 0], [0, pad_H], [0, pad_W], [0, 0]]
        x = tf.pad(x, paddings, "CONSTANT") # Pad with zeros
    return x, pad_H, pad_W # Trả về cả lượng padding để xử lý sau này nếu cần

# Hàm window_partition (như đã sửa, nhưng bỏ raise ValueError nếu đã padding)
def window_partition(x, window_size):
    # Lấy hình dạng động để đảm bảo tính linh hoạt
    B, H, W, C = tf.shape(x)

    # Không cần kiểm tra divisibility ở đây nếu đã padding trước.
    # Nếu vẫn muốn kiểm tra, bạn có thể để lại nhưng đảm bảo padding đã được áp dụng.

    patch_num_H = H // window_size
    patch_num_W = W // window_size

    x = tf.reshape(x, shape=(B, patch_num_H, window_size, patch_num_W, window_size, C))
    x = tf.transpose(x, (0, 1, 3, 2, 4, 5))
    windows = tf.reshape(x, shape=(-1, window_size, window_size, C))

    return windows

# Hàm window_unpartition để nối lại các cửa sổ
def window_unpartition(windows, window_size, H, W, C):
    # Tính toán số lượng cửa sổ theo chiều cao và chiều rộng
    B_prime, _, _, _ = tf.shape(windows) # B_prime là (batch_size * num_windows)

    patch_num_H = H // window_size
    patch_num_W = W // window_size

    # Reshape ngược lại từ (Num_windows * Batch, window_size, window_size, C)
    x = tf.reshape(windows, shape=(-1, patch_num_H, patch_num_W, window_size, window_size, C))

    # Hoán vị ngược lại
    x = tf.transpose(x, (0, 1, 3, 2, 4, 5)) # (batch_size, num_windows_h, window_h, num_windows_w, window_w, C)

    # Reshape thành hình ảnh ban đầu
    x = tf.reshape(x, shape=(-1, H, W, C))
    return x


