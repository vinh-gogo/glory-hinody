def hamy_network(input_shape, k1=32):
    input = Input(shape=input_shape)
    #conv1
    encoded  = Conv2D(k1, (3, 3), activation='elu', padding='same', kernel_regularizer = tf.keras.regularizers.L2(0.0001), activity_regularizer=tf.keras.regularizers.L2(0.0001), bias_regularizer=tf.keras.regularizers.L2(0.0001))(input)
    encoded  = Conv2D(k1, (3, 3), activation='elu', padding='same', kernel_regularizer = tf.keras.regularizers.L2(0.0001), activity_regularizer=tf.keras.regularizers.L2(0.0001), bias_regularizer=tf.keras.regularizers.L2(0.0001))(encoded)
    encoded  = MaxPooling2D((2, 2), padding='same')(encoded)
    #conv2
    encoded  = Conv2D(k1*2, (3, 3), activation='elu', padding='same', kernel_regularizer = tf.keras.regularizers.L2(0.0001), activity_regularizer=tf.keras.regularizers.L2(0.0001), bias_regularizer=tf.keras.regularizers.L2(0.0001))(encoded)
    encoded  = Conv2D(k1*2, (3, 3), activation='elu', padding='same', kernel_regularizer = tf.keras.regularizers.L2(0.0001), activity_regularizer=tf.keras.regularizers.L2(0.0001), bias_regularizer=tf.keras.regularizers.L2(0.0001))(encoded)
    encoded  = MaxPooling2D((2, 2), padding='same')(encoded)
    #conv3
    encoded  = Conv2D(k1*4, (3, 3), activation='elu', padding='same', kernel_regularizer = tf.keras.regularizers.L2(0.0001), activity_regularizer=tf.keras.regularizers.L2(0.0001), bias_regularizer=tf.keras.regularizers.L2(0.0001))(encoded)
    encoded  = Conv2D(k1*4, (3, 3), activation='elu', padding='same', kernel_regularizer = tf.keras.regularizers.L2(0.0001), activity_regularizer=tf.keras.regularizers.L2(0.0001), bias_regularizer=tf.keras.regularizers.L2(0.0001))(encoded)
    encoded  = Conv2D(k1*4, (3, 3), activation='elu', padding='same', kernel_regularizer = tf.keras.regularizers.L2(0.0001), activity_regularizer=tf.keras.regularizers.L2(0.0001), bias_regularizer=tf.keras.regularizers.L2(0.0001))(encoded)
    encoded  = MaxPooling2D((2, 2), padding='same')(encoded)
    #conv4
    encoded  = Conv2D(k1*8, (3, 3), activation='elu', padding='same', kernel_regularizer = tf.keras.regularizers.L2(0.0001), activity_regularizer=tf.keras.regularizers.L2(0.0001), bias_regularizer=tf.keras.regularizers.L2(0.0001))(encoded)
    encoded  = Conv2D(k1*8, (3, 3), activation='elu', padding='same', kernel_regularizer = tf.keras.regularizers.L2(0.0001), activity_regularizer=tf.keras.regularizers.L2(0.0001), bias_regularizer=tf.keras.regularizers.L2(0.0001))(encoded)
    encoded  = Conv2D(k1*8, (3, 3), activation='elu', padding='same', kernel_regularizer = tf.keras.regularizers.L2(0.0001), activity_regularizer=tf.keras.regularizers.L2(0.0001), bias_regularizer=tf.keras.regularizers.L2(0.0001))(encoded)
    encoded  = MaxPooling2D((2, 2), padding='same')(encoded)

    #conv5
    encoded  = Conv2D(k1*16, (3, 3), activation='elu', padding='same', kernel_regularizer = tf.keras.regularizers.L2(0.0001), activity_regularizer=tf.keras.regularizers.L2(0.0001), bias_regularizer=tf.keras.regularizers.L2(0.0001))(encoded)
    encoded  = Conv2D(k1*16, (3, 3), activation='elu', padding='same', kernel_regularizer = tf.keras.regularizers.L2(0.0001), activity_regularizer=tf.keras.regularizers.L2(0.0001), bias_regularizer=tf.keras.regularizers.L2(0.0001))(encoded)
    encoded  = Conv2D(k1*16, (3, 3), activation='elu', padding='same', kernel_regularizer = tf.keras.regularizers.L2(0.0001), activity_regularizer=tf.keras.regularizers.L2(0.0001), bias_regularizer=tf.keras.regularizers.L2(0.0001))(encoded)
    encoded  = MaxPooling2D((2, 2), padding='same')(encoded)

    decoded = Conv2D(k1*32, (3, 3), activation='elu', padding='same', kernel_regularizer = tf.keras.regularizers.L2(0.0001), activity_regularizer=tf.keras.regularizers.L2(0.0001), bias_regularizer=tf.keras.regularizers.L2(0.0001))(encoded)

    decoded = UpSampling2D((2, 2), interpolation='nearest')(decoded)
    decoded  = Conv2D(k1*16, (3, 3), activation='elu', padding='same', kernel_regularizer = tf.keras.regularizers.L2(0.0001), activity_regularizer=tf.keras.regularizers.L2(0.0001), bias_regularizer=tf.keras.regularizers.L2(0.0001))(decoded)
    decoded  = Conv2D(k1*16, (3, 3), activation='elu', padding='same', kernel_regularizer = tf.keras.regularizers.L2(0.0001), activity_regularizer=tf.keras.regularizers.L2(0.0001), bias_regularizer=tf.keras.regularizers.L2(0.0001))(decoded)
