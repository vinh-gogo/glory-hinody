    decoded = UpSampling2D((2, 2), interpolation='nearest')(decoded)
    decoded  = Conv2D(k1*4, (3, 3), activation='elu', padding='same', kernel_regularizer = tf.keras.regularizers.L2(0.0001), activity_regularizer=tf.keras.regularizers.L2(0.0001), bias_regularizer=tf.keras.regularizers.L2(0.0001))(decoded)
    decoded  = Conv2D(k1*4, (3, 3), activation='elu', padding='same', kernel_regularizer = tf.keras.regularizers.L2(0.0001), activity_regularizer=tf.keras.regularizers.L2(0.0001), bias_regularizer=tf.keras.regularizers.L2(0.0001))(decoded)
    decoded  = Conv2D(k1*4, (3, 3), activation='elu', padding='same', kernel_regularizer = tf.keras.regularizers.L2(0.0001), activity_regularizer=tf.keras.regularizers.L2(0.0001), bias_regularizer=tf.keras.regularizers.L2(0.0001))(decoded)

    decoded = UpSampling2D((2, 2), interpolation='nearest')(decoded)
    decoded  = Conv2D(k1*2, (3, 3), activation='elu', padding='same', kernel_regularizer = tf.keras.regularizers.L2(0.0001), activity_regularizer=tf.keras.regularizers.L2(0.0001), bias_regularizer=tf.keras.regularizers.L2(0.0001))(decoded)
    decoded  = Conv2D(k1*2, (3, 3), activation='elu', padding='same', kernel_regularizer = tf.keras.regularizers.L2(0.0001), activity_regularizer=tf.keras.regularizers.L2(0.0001), bias_regularizer=tf.keras.regularizers.L2(0.0001))(decoded)

    decoded = UpSampling2D((2, 2), interpolation='nearest')(decoded)
    decoded  = Conv2D(k1, (3, 3), activation='elu', padding='same', kernel_regularizer = tf.keras.regularizers.L2(0.0001), activity_regularizer=tf.keras.regularizers.L2(0.0001), bias_regularizer=tf.keras.regularizers.L2(0.0001))(decoded)
    decoded  = Conv2D(k1, (3, 3), activation='elu', padding='same', kernel_regularizer = tf.keras.regularizers.L2(0.0001), activity_regularizer=tf.keras.regularizers.L2(0.0001), bias_regularizer=tf.keras.regularizers.L2(0.0001))(decoded)

    decoded = Conv2D(1, (3, 3), activation='sigmoid', padding='same', kernel_regularizer = tf.keras.regularizers.L2(0.0001), activity_regularizer=tf.keras.regularizers.L2(0.0001), bias_regularizer=tf.keras.regularizers.L2(0.0001))(decoded)
    return Model(input, decoded)

